// ------------------------------------------------------------------
// 住宅ローン控除（住宅借入金等特別控除）シミュレーター
//
// 住宅借入金等特別控除は、租税特別措置法第41条に基づく「税額控除」であり、所得金額から
// 差し引く「所得控除」ではない。年末時点の住宅ローン残高に控除率（2022年度税制改正以降は
// 原則0.7%）を乗じた金額（100円未満切り捨て）が、その年分の所得税額から直接差し引かれる。
//
// app/src/lib/payroll/yearEndAdjustment.ts のファイル冒頭コメントに明記されているとおり、
// 本控除は「税額控除であり、年末調整の所得控除ロジックとは枠組みが大きく異なる」ため
// 同モジュールでは意図的に対象外とされている。app/src/lib/tax/estimate.ts（個人事業主の
// 確定申告概算）でも同様に未対応。本モジュールはその欠落を埋める、独立した概算シミュレーター
// として実装する。
//
// 【重要な限定事項（この試算が対応していないこと）】
//   - 実際の借入限度額（年末残高に控除率を乗じる際の上限となる残高）は、住宅の種類
//     （認定長期優良住宅・認定低炭素住宅／ZEH水準省エネ住宅／省エネ基準適合住宅／
//     その他の住宅／既存住宅=中古）、居住開始年、子育て世帯・若者夫婦世帯に該当するか
//     どうかによって2,000万円〜5,000万円の範囲で細かく分かれている。本ツールはこれらの
//     判定を一切行わず、後述する単一の簡易固定上限（HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP）
//     で近似する。
//   - 合計所得金額2,000万円以下であること、床面積50平方メートル以上（合計所得金額
//     1,000万円以下の場合は40平方メートル以上）であることなど、適用要件の判定は行わない
//     （満たしていることを前提とする）。
//   - 控除期間（新築で13年、既存住宅等で10年）にわたる複数年分の試算・合計は行わず、
//     入力された「その年の年末残高」1年分の控除額のみを試算する。
//   - 給与所得者であっても、本控除の適用を受ける最初の年分は年末調整の対象にならず、
//     必ず確定申告が必要（2年目以降は「給与所得者の（特定増改築等）住宅借入金等特別控除
//     申告書」により年末調整で適用可能）という手続き上の要件そのものは、本ツールでは
//     代替できない（下記 HOUSING_LOAN_DEDUCTION_DISCLAIMER を参照）。
//
// このモジュールは、税理士法第2条（税務相談は税理士の独占業務）に抵触しないよう、
// 一般的な制度に基づく概算シミュレーションの提供に留める。個別の物件・契約内容についての
// 判断や助言は行わない。
//
// 【重要】このファイルは app/src/lib/tax/estimate.ts に依存しない、完全に自己完結した
// モジュールとして実装している（pensionSavingsSimulator.ts と同じ方針）。他のエージェントが
// estimate.ts を並行して編集中のため、依存すると競合・破壊的変更のリスクがある。
//
// 出典: 国税庁タックスアンサー No.1213-1「認定住宅の新築等をした場合（住宅借入金等特別控除）」
// および国土交通省・財務省公表の「住宅ローン控除の概要」（2022年度・2024年度税制改正資料）。
// 制度は税制改正のたびに変更されるため、実際の申告時には必ず国税庁の最新の発表内容と
// 照合すること。
// ------------------------------------------------------------------

/**
 * 住宅借入金等特別控除の控除率。2022年度税制改正により、それ以前の1.0%から0.7%に
 * 引き下げられた（2022年以降に居住を開始した場合に適用される現行の率）。
 * 制度改正により将来変更される可能性があるため、必ず国税庁の最新の公表情報で再確認すること
 * （本値は実装時点＝2026年時点の目安）。
 */
export const HOUSING_LOAN_DEDUCTION_RATE = 0.007;

/**
 * 本ツールが仮定する、年末残高に控除率を乗じる際の簡易・固定の借入限度額（円）。
 *
 * 実際の借入限度額は住宅の種類・居住開始年・世帯属性によって2,000万円〜5,000万円の
 * 範囲で異なるが、本ツールはその判定を行わないため、2024年〜2025年入居の新築住宅で
 * 最も一般的な区分の一つである「省エネ基準適合住宅」の借入限度額（3,000万円）を
 * 簡易的な代表値として採用する。
 *
 * 【注意】この値は次のようなケースには当てはまらない:
 *   - 認定長期優良住宅・認定低炭素住宅（上限は最大4,500万円、子育て世帯・若者夫婦世帯は
 *     最大5,000万円）
 *   - ZEH水準省エネ住宅（上限3,500万円、子育て世帯・若者夫婦世帯は4,500万円）
 *   - 省エネ基準に適合しない「その他の住宅」（原則対象外。2023年末までの建築確認等
 *     一定の経過措置がある場合のみ2,000万円）
 *   - 既存住宅（中古、上限は原則2,000万円、一定の高い省エネ性能を満たす場合3,000万円）
 * 実際の借入限度額は、住宅性能証明書・登記事項証明書等に基づき、必ずご自身（または
 * 税理士等の専門家）で確認すること。
 */
export const HOUSING_LOAN_DEDUCTION_SIMPLIFIED_LOAN_BALANCE_CAP = 30_000_000;

/**
 * 上記の簡易借入限度額に控除率を乗じた、1年あたりの控除額の簡易上限（円）。
 * = HOUSING_LOAN_DEDUCTION_SIMPLIFIED_LOAN_BALANCE_CAP × HOUSING_LOAN_DEDUCTION_RATE
 * （100円未満の端数は生じない値のため、そのまま定数化している）
 */
export const HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP = Math.floor(
  (HOUSING_LOAN_DEDUCTION_SIMPLIFIED_LOAN_BALANCE_CAP * HOUSING_LOAN_DEDUCTION_RATE) / 100
) * 100;

export const HOUSING_LOAN_DEDUCTION_DISCLAIMER =
  "これは住宅借入金等特別控除（住宅ローン控除）に関する一般的な制度に基づく概算試算（シミュレーション）であり、個別具体的な税務相談・助言（税理士法上の税務相談）には該当しません。実際の借入限度額は、住宅の種類（認定住宅・ZEH水準省エネ住宅・省エネ基準適合住宅・その他の住宅・既存住宅等）や居住開始年、子育て世帯・若者夫婦世帯への該当有無によって、本ツールが仮定する簡易な借入限度額とは異なります。また、合計所得金額・床面積などの適用要件の判定は行っていません。給与所得者であっても、本控除の適用を受ける最初の年分は年末調整では処理できず、必ずご自身で確定申告を行う必要があります（本ツールはこの確定申告の手続き・書類作成を代行するものではなく、その必要性を代替するものでもありません）。住宅の取得時期・種類、共有名義、繰上返済、連帯債務など特殊な事情がある場合は、税理士等の専門家にご相談ください。";

export interface HousingLoanDeductionInput {
  /** 年末時点の住宅ローン残高（円）。連帯債務の場合はご自身の負担割合分の残高を入力する想定 */
  yearEndLoanBalance: number;
  /**
   * 控除率。省略時は HOUSING_LOAN_DEDUCTION_RATE（現行0.7%）を使用する。
   * 制度改正前（2021年以前入居、1.0%等）を試算したい場合にのみ明示的に指定する。
   */
  creditRate?: number;
  /**
   * 1年あたりの控除額の上限（円）。省略時は HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP
   * （簡易仮定：省エネ基準適合住宅・借入限度額3,000万円相当）を使用する。
   * 認定住宅等、実際の住宅の区分に応じた正しい上限が分かっている場合は、その値
   * （借入限度額 × 控除率）を明示的に指定することで、より実態に近い試算ができる。
   */
  annualCreditCap?: number;
}

export interface HousingLoanDeductionResult {
  yearEndLoanBalance: number;
  creditRate: number;
  /** 上限を適用する前の控除額（年末残高 × 控除率、100円未満切り捨て） */
  rawAnnualCredit: number;
  /** この試算で適用した1年あたりの控除額の上限（円） */
  annualCreditCap: number;
  /** 上限によって控除額が抑えられたかどうか（rawAnnualCredit が annualCreditCap を超えていたか） */
  cappedByLimit: boolean;
  /** 実際に控除されると見込まれる年間の税額控除額（概算） = min(rawAnnualCredit, annualCreditCap) */
  estimatedAnnualCredit: number;
  disclaimer: string;
  assumptions: string[];
}

function assertFiniteNonNegative(value: number, label: string): void {
  if (!Number.isFinite(value)) {
    throw new Error(`${label}は数値で入力してください。`);
  }
  if (value < 0) {
    throw new Error(`${label}は0以上の数値で入力してください。`);
  }
}

/**
 * 年末時点の住宅ローン残高から、住宅借入金等特別控除（住宅ローン控除）による
 * その年分の税額控除額を概算するシミュレーション。
 *
 * 控除額は「年末残高 × 控除率」を計算し、100円未満の端数を切り捨てた金額とする
 * （この端数処理自体は近似ではなく、法定の計算方法である）。この金額と1年あたりの
 * 控除額の上限（annualCreditCap、省略時は簡易仮定値）とを比較し、小さい方を
 * 実際の控除見込み額（estimatedAnnualCredit）とする。
 *
 * このツールが試算するのは「1年分（入力された年末残高の年）」の控除額のみであり、
 * 控除期間全体（新築で13年、既存住宅等で10年）にわたる複数年分の合計は試算しない
 * （年ごとに年末残高を入力し、都度この関数を呼び出すことを想定している）。
 *
 * @throws 年末残高・控除率・上限のいずれかが数値でない、または0未満の場合
 */
export function calculateHousingLoanDeduction(input: HousingLoanDeductionInput): HousingLoanDeductionResult {
  const {
    yearEndLoanBalance,
    creditRate = HOUSING_LOAN_DEDUCTION_RATE,
    annualCreditCap = HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP,
  } = input;

  assertFiniteNonNegative(yearEndLoanBalance, "年末時点の住宅ローン残高");
  assertFiniteNonNegative(creditRate, "控除率");
  assertFiniteNonNegative(annualCreditCap, "1年あたりの控除額の上限");

  // 控除額は円未満ではなく100円未満切り捨て（住宅借入金等特別控除の法定の端数処理）
  const rawAnnualCredit = Math.floor((yearEndLoanBalance * creditRate) / 100) * 100;
  const cappedByLimit = rawAnnualCredit > annualCreditCap;
  const estimatedAnnualCredit = Math.min(rawAnnualCredit, annualCreditCap);

  return {
    yearEndLoanBalance,
    creditRate,
    rawAnnualCredit,
    annualCreditCap,
    cappedByLimit,
    estimatedAnnualCredit,
    disclaimer: HOUSING_LOAN_DEDUCTION_DISCLAIMER,
    assumptions: [
      `控除率は${(creditRate * 100).toFixed(2)}%を使用しています（2022年度税制改正以降の現行率は0.7%。2021年以前に居住を開始した場合は1.0%等、異なる率が適用されることがあります）`,
      annualCreditCap === HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP
        ? `1年あたりの控除額の上限は、借入限度額3,000万円（省エネ基準適合住宅の新築を仮定した簡易値）× 控除率で計算した${HOUSING_LOAN_DEDUCTION_SIMPLIFIED_ANNUAL_CAP.toLocaleString(
            "ja-JP"
          )}円を使用しています。認定長期優良住宅・ZEH水準省エネ住宅・既存住宅（中古）等、実際の住宅の区分によって借入限度額（延いては上限額）は2,000万円〜5,000万円の範囲で異なります`
        : "1年あたりの控除額の上限は、入力された値をそのまま使用しています",
      "控除額は「年末残高×控除率」を100円未満切り捨てで計算しています（この端数処理は近似ではなく法定の計算方法です）",
      "控除期間（新築住宅で13年間、既存住宅等で10年間）のうち、この試算は入力された年末残高1年分の控除額のみを計算しています。年ごとに年末残高を入力し、必要な年数分繰り返し試算してください",
      "合計所得金額2,000万円以下であること、床面積50平方メートル以上（合計所得金額1,000万円以下の場合は40平方メートル以上）であることなど、その他の適用要件は判定していません（満たしていることを前提としています）",
      "本控除は税額控除であり、所得税額から直接差し引かれます（所得控除のように課税所得を減らすものではありません）。所得税額から控除しきれない額がある場合の住民税からの控除（住宅ローン控除の住民税への振替）は考慮していません",
      "給与所得者であっても、本控除の適用を受ける最初の年分は年末調整では処理できず、必ず確定申告が必要です。2年目以降は「給与所得者の住宅借入金等特別控除申告書」により年末調整で適用できますが、この手続き自体は本ツールでは代替できません",
    ],
  };
}
