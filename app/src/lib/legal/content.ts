export function getLegalDocument(id: LegalDocumentId): LegalDocument {
  const doc = legalDocuments.find((d) => d.id === id);
  if (!doc) {
    // legalDocuments は上記のとおり3件を静的に定義しているため、
    // 型的に到達不能なはずだが、将来の変更に備えて明示的にエラーを投げる。
    throw new Error(`Unknown legal document id: ${id}`);
  }
  return doc;
}

/** 段落区切り("\n\n")で本文を分割する。JSXでの <p> 描画用のヘルパー。 */
export function splitParagraphs(body: string): string[] {
  return body
    .split("\n\n")
    .map((p) => p.trim())
    .filter((p) => p.length > 0);
}
